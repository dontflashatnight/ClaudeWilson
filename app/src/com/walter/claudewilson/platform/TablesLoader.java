package com.walter.claudewilson.platform;

import android.content.Context;

import com.walter.claudewilson.model.Tables;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.Charset;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Loads the catalog assets and the package denylist, and parses them into {@link Tables}.
 *
 * <p>Cached per process: the old code re-read and re-parsed the same files on every call. A
 * missing asset is logged and simply leaves that table empty, which every rule turns into
 * {@code UNKNOWN} instead of a silent pass.
 */
public final class TablesLoader {
    private static final String DIRECTORY = "catalog/";
    private static final Charset UTF_8 = Charset.forName("UTF-8");
    private static final String DENYLIST = "denylist.txt";
    private static final String DENYLIST_OVERRIDE = "denylist-override.txt";
    private static final String[] NAMES = {
            Tables.SU_PATHS,
            Tables.RW_DIRS,
            Tables.MCC,
            Tables.CARRIERS,
            Tables.PACKAGE_KEYWORDS,
            Tables.LABEL_KEYWORDS,
            Tables.EMULATOR_SIGNATURES,
            Tables.VENDOR_WORDS,
            Tables.LEAKED_CAS,
            Tables.VENDOR_FAMILIES,
            Tables.PERSONAS,
    };

    private static Tables cached;

    private TablesLoader() {
    }

    public static synchronized Tables load(Context context) {
        if (cached != null) {
            return cached;
        }
        Map<String, String> raw = new LinkedHashMap<String, String>();
        for (String name : NAMES) {
            try (InputStream stream = context.getAssets().open(DIRECTORY + name + ".txt")) {
                raw.put(name, readAll(stream));
            } catch (Exception e) {
                Diag.warn("catalog", "cannot load " + name, e);
            }
        }
        // The denylist keeps its own [section] format because it is regenerated by a script and
        // hot-updated on device; both files feed the same tables.
        StringBuilder root = new StringBuilder();
        StringBuilder modern = new StringBuilder();
        StringBuilder keywords = new StringBuilder();
        try (InputStream stream = context.getAssets().open(DENYLIST)) {
            appendDenylist(readAll(stream), root, modern, keywords);
        } catch (Exception e) {
            Diag.warn("catalog", "cannot load " + DENYLIST, e);
        }
        File override = new File(context.getExternalFilesDir(null), DENYLIST_OVERRIDE);
        if (override.isFile()) {
            FileInputStream stream = null;
            try {
                stream = new FileInputStream(override);
                appendDenylist(readAll(stream), root, modern, keywords);
            } catch (Exception e) {
                Diag.warn("catalog", "cannot read " + DENYLIST_OVERRIDE, e);
            } finally {
                if (stream != null) {
                    try {
                        stream.close();
                    } catch (IOException ignored) {
                        // nothing useful to do while closing a read-only stream
                    }
                }
            }
        }
        raw.put(Tables.ROOT_PACKAGES, root.toString());
        raw.put(Tables.MODERN_PACKAGES, modern.toString());
        String catalogKeywords = raw.get(Tables.PACKAGE_KEYWORDS);
        raw.put(Tables.PACKAGE_KEYWORDS,
                (catalogKeywords == null ? "" : catalogKeywords + "\n") + keywords);
        cached = Tables.parse(raw);
        Diag.info("catalog", "loaded version=" + cached.version());
        return cached;
    }

    /** Splits the [target] / [modern] / [keywords] sections into the three builders. */
    private static void appendDenylist(String text, StringBuilder root, StringBuilder modern,
                                       StringBuilder keywords) {
        StringBuilder sink = null;
        for (String rawLine : text.split("\n")) {
            String line = rawLine.trim();
            if (line.isEmpty() || line.startsWith("#")) {
                continue;
            }
            if (line.startsWith("[")) {
                if (line.contains("target")) {
                    sink = root;
                } else if (line.contains("modern")) {
                    sink = modern;
                } else if (line.contains("keywords")) {
                    sink = keywords;
                }
                continue;
            }
            if (sink == null) {
                continue;
            }
            if (sink.length() > 0) {
                sink.append('\n');
            }
            sink.append(line);
        }
    }

    private static String readAll(InputStream stream) throws IOException {
        ByteArrayOutputStream buffer = new ByteArrayOutputStream();
        byte[] chunk = new byte[4096];
        int read;
        while ((read = stream.read(chunk)) > 0) {
            buffer.write(chunk, 0, read);
        }
        return new String(buffer.toByteArray(), UTF_8);
    }
}
